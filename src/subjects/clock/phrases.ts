function minutesText(n: number): string {
  if (n === 1) return 'דַּקָּה'
  if (n === 2) return 'שְׁתֵּי דַּקּוֹת'
  const word = n < 10 ? UNITS[n] : n < 20 ? TEENS[n - 10] : n === 20 ? 'עֶשְׂרִים' : `עֶשְׂרִים ${AND_UNITS[n - 20]}`
  return `${word} דַּקּוֹת`
}

const blocks: Record<string, string> = {}
HOURS.forEach((w, i) => {
  blocks[`clock.h.${i + 1}`] = w
  blocks[`clock.to.${i + 1}`] = TO_HOURS[i]!
})
for (let m = 1; m < 30; m++) blocks[`clock.min.${m}`] = minutesText(m)

